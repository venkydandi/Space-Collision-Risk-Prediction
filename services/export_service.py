"""Export and report generation service."""
from __future__ import annotations

import io
import pandas as pd

from config.settings import FEATURES


def generate_results_csv(results_df: pd.DataFrame) -> bytes:
    """
    Generate downloadable CSV containing all audit columns and original columns.
    
    Preserves original row order and all records (accepted and rejected).
    """
    buffer = io.StringIO()
    results_df.to_csv(buffer, index=False, encoding="utf-8")
    return buffer.getvalue().encode("utf-8-sig")


def generate_cdm_template_csv() -> bytes:
    """Generate empty template CSV with canonical headers and sample row."""
    template_cols = ["event_id"] + FEATURES
    example_row = {
        "event_id": "EXAMPLE-001",
        "time_to_tca": 2.45,
        "max_risk_estimate": -5.20,
        "max_risk_scaling": 15.0,
        "miss_distance": 1200.0,
        "mahalanobis_distance": 14.5,
        "c_obs_used": 30.0,
        "c_object_type": "DEBRIS",
    }
    df = pd.DataFrame([example_row], columns=template_cols)
    buffer = io.StringIO()
    df.to_csv(buffer, index=False, encoding="utf-8")
    return buffer.getvalue().encode("utf-8-sig")


